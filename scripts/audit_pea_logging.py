"""Bounded logging/capture reference audit using REA identities and IL exports.

Reads original file bytes and exported metadata only. No target code executes.
Run Reconstruct.ps1 first if the ignored REA evidence has not been generated.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
manifest = json.loads((ROOT / 'exam-input-manifest.json').read_text(encoding='utf-8-sig'))
capture_patterns = [
    'SetWindowsHookEx', 'GetAsyncKeyState', 'GetKeyState', 'RegisterRawInputDevices',
    'CopyFromScreen', 'BitBlt', 'PrintWindow', 'WaveIn', 'WasapiCapture',
    'StartRecording', 'NewFrame', 'SaveScreenImage', 'Clipboard',
]
report = {
    'scope': 'Static direct-call review of the eight selected original PEA application assemblies',
    'method_index_source': 'Retained REA identities and original method exports generated by Reconstruct.ps1',
    'capture_api_search_patterns': capture_patterns,
    'packs': {},
    'limitations': [
        'No client, downloaded GUI, device capture or exam server was executed.',
        'No direct call found does not establish absence of behavior in the deployed system.',
        'The downloaded PEAClient.FrmPEAClient and server implementations are outside the supplied files.',
        'Capture-pattern matching is a bounded search, not a complete detector for every possible capture technique.',
        'Third-party Ionic.Zip and the PRN debugger host are outside this 410-method application index.',
        'Message declarations do not establish actual event contents, server persistence, retention or alert timing.',
    ],
}
for pack, expected in [('PEA-CSD', 197), ('PEA-PRN', 213)]:
    artifacts, calls = [], []
    for assembly in ('PEALogin', 'IRemote', 'GradeLib', 'EncryptData'):
        name = assembly + ('.exe' if assembly == 'PEALogin' else '.dll')
        entry = next(e for e in manifest if e['Build'] == pack and Path(e['Path']).name == name)
        digest = hashlib.sha256((ROOT / entry['Path']).read_bytes()).hexdigest()
        members = json.loads((ROOT / f'evidence/{pack}.{assembly}.members.json').read_text(encoding='utf-8-sig'))['normalized_result']
        if digest.upper() != entry['SHA256'].upper() or digest.upper() != members['artifact']['sha256'].upper():
            raise RuntimeError(f'Input/evidence identity mismatch: {pack}/{name}')
        rows = json.loads((ROOT / f'evidence/method-exports/{pack}.{assembly}/method-index.json').read_text(encoding='utf-8-sig'))
        if len(rows) != len(members['methods']):
            raise RuntimeError(f'Incomplete method export: {pack}/{name}')
        artifacts.append({'assembly': name, 'sha256': digest, 'mvid': members['module']['mvid'], 'methods': len(rows)})
        for row in rows:
            for call in row.get('calls') or []:
                calls.append({'assembly': name, 'token': row['token'], 'method': row['type'] + '.' + row['name'], 'offset': call['offset'], 'target': call['target']})
    count = sum(a['methods'] for a in artifacts)
    if count != expected:
        raise RuntimeError(f'Unexpected method count for {pack}: {count}')

    def select(patterns):
        return [c for c in calls if any(p in c['target'] for p in patterns)]

    report['packs'][pack] = {
        'artifacts': artifacts,
        'methods_indexed': count,
        'remote_log_direct_calls': select(['IRemoteServer::Log']),
        'remote_submit_direct_calls': select(['IRemoteServer::Submit']),
        'registration_direct_calls': select(['IRemoteServer::ConductTest']),
        'registration_assignments': select(['RegisterData::set_']),
        'history_construction_direct_calls': select(['SubmitHistory::.ctor']),
        'solution_construction_direct_calls': select(['SubmitSolution::.ctor']),
        'capture_api_pattern_hits': select(capture_patterns),
        'archive_write_direct_calls': select(['Ionic.Zip.ZipFile::AddDirectory', 'Ionic.Zip.ZipFile::Save', 'Ionic.Zip.ZipEntry::Extract']),
    }
(ROOT / 'analysis').mkdir(exist_ok=True)
(ROOT / 'analysis/pea-logging.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
print(json.dumps({pack: {key: len(data[key]) for key in ('remote_log_direct_calls', 'remote_submit_direct_calls', 'capture_api_pattern_hits')} for pack, data in report['packs'].items()}))
